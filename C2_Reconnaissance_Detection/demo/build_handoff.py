"""Build the Component 2 handoff package: every file needed beyond `git checkout` (Git-ignored artifacts).

Writes <repo>/handoff/C2_handoff_package.zip (paths relative to the repository root, extract into the root) and
<repo>/handoff/HANDOFF_MANIFEST.json (also inside the zip): every packaged file with size and SHA-256, the Git
commit the package was built against, and every intentionally omitted group with its size and reason.
Standard library only.  Usage:  python C2_Reconnaissance_Detection/demo/build_handoff.py
"""
from __future__ import annotations

import datetime as dt
import hashlib
import json
import subprocess
import zipfile
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
OUT = REPO / "handoff"
TB = "component2_testbed"
FV = f"{TB}/data/final_v1"
PREPARED = json.loads((REPO / "C2_Reconnaissance_Detection/demo_bundle/runs/index.json").read_text())
PREPARED_IDS = [r["run_id"] for r in PREPARED]
PILOT_BIG = {"pilot_requests_labeled_with_history.parquet", "causal_context_index.parquet"}

# (group, purpose, list of glob patterns relative to the repo root)
REQUIRED = [
    ("demo_bundle", "Frontend/backend runtime: frozen models (RF joblib, LSTM weights), thresholds, prepared held-out "
     "runs, upload samples with reference scores, final reports", ["C2_Reconnaissance_Detection/demo_bundle/**/*"]),
    ("frontend_build", "Built React frontend served by the demo server (no Node.js needed)",
     ["C2_Reconnaissance_Detection/frontend/dist/**/*"]),
    ("dashboard_metrics", "Request-pooled metrics and exact confusion counts aggregated from existing frozen test predictions; no model fitting or new test scoring",
     ["C2_Reconnaissance_Detection/demo/metrics_report.json"]),
    ("final_models", "Frozen fitted models, thresholds, CV selection, validation/test scores and reports, test-opening logs",
     [f"{FV}/models/*"]),
    ("model_inputs", "Exact train/validation/test model inputs (19 step features, 20-request windows, B3 statistics, "
     "metadata) to re-run or inspect training/selection with c2tb/train_models.py", [f"{FV}/model_inputs/**/*"]),
    ("collection_evidence", "Collection manifests, gate results, per-run acceptance/tshark/parse summaries and run "
     "manifests (PCAP hashes) for all 384 runs; collection/processing/training logs",
     [f"{FV}/collection_manifest*.json", f"{FV}/analysis/*", f"{FV}/derived/*/acceptance.json",
      f"{FV}/derived/*/tshark_check.json", f"{FV}/derived/*/parse_stats.json", f"{FV}/runs/*/run_manifest.json",
      f"{TB}/data/*.log"]),
    ("pilot_evidence", "Pilot v1-v3 summaries, gates, diagnostics tables and per-run acceptance (bulk parquet excluded)",
     [f"{TB}/data/pilot_*/collection_manifest.json", f"{TB}/data/pilot_*/analysis/*",
      f"{TB}/data/pilot_*/derived/*/acceptance.json", f"{TB}/data/pilot_*/derived/*/tshark_check.json"]),
    ("prepared_run_raw", "Complete raw evidence of the 8 prepared held-out runs: PCAP, ledgers, plan, clock log, "
     "logs, parsed ADUs/requests (Wireshark proof, re-parsing)",
     [f"{FV}/runs/{r}/*" for r in PREPARED_IDS] + [f"{FV}/derived/{r}/*" for r in PREPARED_IDS]),
]
OMITTED = [
    ("Raw acquisition of the other 376 final runs", [f"{FV}/runs/**/*"], "Captures/ledgers/plans; every PCAP hash is kept "
     "in the shipped run manifests. Not needed to run the demo, load models, replay, score or reproduce training."),
    ("Bulk parsed tables of the other final runs", [f"{FV}/derived/**/*"], "Per-run parsed ADU/request parquet files; "
     "regenerable from the raw captures with c2tb.process_run. Model inputs are shipped instead."),
    ("Pilot raw runs and bulk pilot tables", [f"{TB}/data/pilot_*/runs/**/*", f"{TB}/data/pilot_*/derived/**/*",
                                              f"{TB}/data/pilot_*/analysis/*.parquet"],
     "Pilot captures and per-request tables; pilot summaries and gates are shipped."),
    ("Smoke-test collections", [f"{TB}/data/smoke_test*/**/*"], "Tooling checks, excluded from all analysis."),
    ("Frozen plan bodies", [f"{TB}/final/frozen/plans/*", f"{TB}/final/bench/plans/*"],
     "Regenerated byte-identically by c2tb.freeze_plans from configs/final_v1.json; hashes are in the tracked "
     "frozen_plan_manifest.json."),
    ("Superseded packages", [f"{TB}/data/C2_viva_package.zip", f"{TB}/data/HOW_TO_DEMO.md",
                             "C2_Reconnaissance_Detection/C2_viva_demo_package.zip"], "Replaced by this handoff package."),
    ("Local environments and caches", ["C2_Reconnaissance_Detection/demo/.venv/**/*",
                                       "C2_Reconnaissance_Detection/frontend/node_modules/**/*",
                                       "component2_forensic_review/.deps/**/*"],
     "Recreated by setup (pip) or npm; the audit's vendored packages are pip-installable."),
    ("Forensic-audit bulk evidence", ["component2_forensic_review/evidence/**/*"],
     "Large intermediate CSV/NPY files of the CIC audit (Git-ignored); regenerable only with the external 15.6 GB "
     "CIC archive. Audit reports and summary tables are tracked in Git."),
]


def sha(p: Path) -> str:
    h = hashlib.sha256()
    with open(p, "rb") as f:
        for b in iter(lambda: f.read(1 << 20), b""):
            h.update(b)
    return h.hexdigest()


def expand(patterns):
    out = []
    for pat in patterns:
        out += [p for p in REPO.glob(pat) if p.is_file()]
    return out


def git(*a):
    return subprocess.run(["git", "-C", str(REPO), *a], capture_output=True, text=True).stdout.strip()


def main():
    OUT.mkdir(exist_ok=True)
    files, groups = {}, []
    for name, purpose, pats in REQUIRED:
        fs = [p for p in expand(pats) if not (name == "pilot_evidence" and p.name in PILOT_BIG)]
        for p in fs:
            rel = p.relative_to(REPO).as_posix()
            files[rel] = {"bytes": p.stat().st_size, "sha256": sha(p), "group": name}
        groups.append({"group": name, "purpose": purpose, "files": len(fs), "bytes": sum(p.stat().st_size for p in fs)})
    ignored = set(git("ls-files", "--others", "--ignored", "--exclude-standard").splitlines())
    omitted, seen = [], set()
    for name, pats, reason in OMITTED:  # only Git-ignored files that are not packaged (tracked files come from Git)
        fs = [p for p in expand(pats) if (r := p.relative_to(REPO).as_posix()) in ignored and r not in files
              and r not in seen]
        seen.update(p.relative_to(REPO).as_posix() for p in fs)
        omitted.append({"what": name, "files": len(fs), "bytes": sum(p.stat().st_size for p in fs), "reason": reason})
    manifest = {
        "package": "C2_handoff_package.zip", "extract_to": "repository root (the folder containing C2_Reconnaissance_Detection)",
        "built_utc": dt.datetime.now(dt.timezone.utc).isoformat(timespec="seconds"),
        "git": {"branch": git("branch", "--show-current"), "commit": git("rev-parse", "HEAD"),
                "uncommitted_changes": bool(git("status", "--porcelain")),
                "tracked_files": len(git("ls-files").splitlines())},
        "required_groups": groups, "omitted": omitted,
        "ignored_files_not_classified": sorted(ignored - set(files) - seen - {"HANDOFF_MANIFEST.json"}),
        "files": dict(sorted(files.items())),
    }
    (OUT / "HANDOFF_MANIFEST.json").write_text(json.dumps(manifest, indent=1))
    zpath = OUT / "C2_handoff_package.zip"
    with zipfile.ZipFile(zpath, "w", zipfile.ZIP_DEFLATED, compresslevel=6) as z:
        for rel in manifest["files"]:
            z.write(REPO / rel, rel)
        z.write(OUT / "HANDOFF_MANIFEST.json", "HANDOFF_MANIFEST.json")
    zsha = sha(zpath)
    (OUT / "C2_handoff_package.zip.sha256").write_text(f"{zsha}  C2_handoff_package.zip\n")
    print(f"{zpath}  {zpath.stat().st_size / 1e6:.1f} MB  sha256 {zsha}")
    print(f"{len(files)} files packaged, {sum(f['bytes'] for f in files.values()) / 1e6:.1f} MB uncompressed")
    for g in groups:
        print(f"  {g['group']:20s} {g['files']:5d} files {g['bytes'] / 1e6:8.1f} MB")
    for o in omitted:
        print(f"  omitted: {o['what']:45s} {o['files']:6d} files {o['bytes'] / 1e6:9.1f} MB")


if __name__ == "__main__":
    main()
